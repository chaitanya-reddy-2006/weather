-- WeatherCast database schema
-- Matches src/App.jsx and the existing public.weather_readings table.
-- Safe to run on an existing project: CREATE TABLE IF NOT EXISTS does not replace existing rows.

create table if not exists public.weather_readings (
  id bigint generated by default as identity primary key,
  timestamp timestamptz not null default now(),
  temperature_c double precision,
  humidity_percent double precision,
  pressure_hpa double precision,
  wind_speed_kmh double precision,
  rainfall_mm double precision,
  air_quality double precision,
  uv_index double precision,
  weather_status text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.weather_readings enable row level security;
alter table public.admin_users enable row level security;

grant select on public.weather_readings to anon, authenticated;
grant insert, update, delete on public.weather_readings to authenticated;
grant select on public.admin_users to authenticated;

drop policy if exists "Public can read weather readings" on public.weather_readings;
create policy "Public can read weather readings"
on public.weather_readings
for select
to anon, authenticated
using (true);

drop policy if exists "Admins can insert weather readings" on public.weather_readings;
create policy "Admins can insert weather readings"
on public.weather_readings
for insert
to authenticated
with check (
  exists (select 1 from public.admin_users where user_id = auth.uid())
);

drop policy if exists "Admins can update weather readings" on public.weather_readings;
create policy "Admins can update weather readings"
on public.weather_readings
for update
to authenticated
using (exists (select 1 from public.admin_users where user_id = auth.uid()))
with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Admins can delete weather readings" on public.weather_readings;
create policy "Admins can delete weather readings"
on public.weather_readings
for delete
to authenticated
using (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "Users can read own admin allowlist entry" on public.admin_users;
create policy "Users can read own admin allowlist entry"
on public.admin_users
for select
to authenticated
using (user_id = auth.uid());
